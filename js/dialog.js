function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function getReply(text) {
  for (const entry of KEYWORD_REPLIES) {
    if (entry.keys.some((k) => text.includes(k))) return pick(entry.replies);
  }
  return pick(DEFAULT_REPLIES);
}

export function getSlapLine(count) {
  if (SLAP_MILESTONES[count]) return SLAP_MILESTONES[count];
  return pick(SLAP_LINES);
}

export function getStageLine(stage) {
  const set = STAGE_LINES[stage] || STAGE_LINES[0];
  return pick(set);
}

export function getEndingLine() {
  return pick(ENDING_LINES);
}
